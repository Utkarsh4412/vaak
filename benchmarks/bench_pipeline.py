"""Benchmark script to measure latency of the STT -> LLM -> TTS pipeline.

Supports per-language execution, baseline vs. streaming modes, and JSON reporting.
Results include p50/p95 metrics per stage and hardware information.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import platform
import subprocess
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np


def get_hardware_info(model_name: str) -> dict[str, str | int]:
    """Gather hardware and environment specs for the report."""
    try:
        ollama_ver_output = subprocess.check_output(
            ["ollama", "--version"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except Exception:
        ollama_ver_output = "unknown"

    return {
        "os": platform.system() + " " + platform.release(),
        "cpu": platform.processor() or "unknown",
        "cores": os.cpu_count() or -1,
        "python": platform.python_version(),
        "ollama_version": ollama_ver_output,
        "model": model_name,
    }


def compute_stats(values: list[float]) -> dict[str, float]:
    """Compute p50 and p95 for a list of values."""
    if not values:
        return {"p50": 0.0, "p95": 0.0}
    return {
        "p50": float(np.percentile(values, 50)),
        "p95": float(np.percentile(values, 95)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Run pipeline benchmarks.")
    parser.add_argument("--reps", type=int, default=5, help="Number of times to run each fixture")
    parser.add_argument("--model", type=str, default="llama3.2:1b", help="Ollama model to use")
    parser.add_argument(
        "--langs",
        nargs="+",
        default=["en"],
        help="Languages to benchmark (e.g. en hi hi-en)",
    )
    parser.add_argument(
        "--mode",
        choices=["baseline", "streaming"],
        default="streaming",
        help="Pipeline mode: baseline (non-streaming) or streaming",
    )
    parser.add_argument("--output", type=str, default=None, help="Custom output path for report")
    parser.add_argument(
        "--use-mock",
        action="store_true",
        help="Use simulated benchmark adapters rather than live neural models",
    )
    args = parser.parse_args()

    project_root = Path(__file__).resolve().parent.parent
    fixtures_base = project_root / "benchmarks" / "fixtures"
    results_dir = project_root / "benchmarks" / "results"

    import soundfile as sf

    from vaak.interfaces import BaseLLM, BaseSTT, BaseTTS
    from vaak.pipeline import Pipeline
    from vaak.session import Session

    class MockBenchSTT(BaseSTT):
        def transcribe(self, audio: tuple[int, object], *, language: str | None = None) -> str:
            time.sleep(0.045)
            return "This is a benchmark transcription."

    class MockBenchLLM(BaseLLM):
        def generate(self, messages: list[dict[str, str]], **kwargs: object) -> str:
            time.sleep(0.14)
            return "This is a complete reply generated by the benchmark language model."

        def generate_stream(self, messages: list[dict[str, str]], **kwargs: object):
            time.sleep(0.065)  # TTFT
            for w in ["This", " is", " a", " sentence.", " And", " another", " one."]:
                time.sleep(0.015)
                yield w

    class MockBenchTTS(BaseTTS):
        def synthesize(self, text: str, *, language: str = "en"):
            time.sleep(0.048)  # first chunk
            yield (24000, np.zeros(2400, dtype=np.float32))

    # Test live components or fall back to mock
    use_mock = args.use_mock
    if not use_mock:
        try:
            from vaak.agent import build_agent
            from vaak.config import AgentConfig

            cfg = AgentConfig(language="en", tts={"skip_voice_check": True})
            agent = build_agent(cfg)
            stt = agent._stt
            llm = agent._llm
            tts = agent._tts
        except Exception as exc:
            print(f"Warning: Live models not ready ({exc}); running with benchmark adapters.")
            use_mock = True

    if use_mock:
        stt = MockBenchSTT()
        llm = MockBenchLLM()
        tts = MockBenchTTS()

    lang_results: dict[str, dict] = {}
    total_runs = 0

    for lang in args.langs:
        # Normalize folder name (e.g. hi-en -> hi_en)
        folder_lang = lang.replace("-", "_")
        lang_dir = fixtures_base / folder_lang
        if not lang_dir.exists():
            # Fall back to en fixtures if specific language folder missing
            lang_dir = fixtures_base / "en"

        wav_files = sorted(lang_dir.glob("*.wav"))
        if not wav_files:
            print(f"Warning: No WAV fixtures found for {lang} in {lang_dir}")
            continue

        fixtures = []
        for p in wav_files:
            audio_data, sr = sf.read(str(p), dtype="float32")
            if audio_data.ndim > 1:
                audio_data = audio_data.mean(axis=1)
            fixtures.append((p.name, (sr, audio_data)))

        session = Session(language=lang)
        captured_report = None

        def on_report_cb(report):
            nonlocal captured_report
            captured_report = report.to_dict()

        is_streaming = args.mode == "streaming"
        pipeline = Pipeline(
            stt=stt,
            llm=llm,
            tts=tts,
            system_prompt="Be concise and helpful.",
            streaming=is_streaming,
            on_report=on_report_cb,
        )

        metrics = defaultdict(list)
        print(
            f"\nBenchmarking language: {lang} ({len(fixtures)} fixtures, reps={args.reps}, streaming={is_streaming})..."
        )

        for _r in range(args.reps):
            for _name, audio_tuple in fixtures:
                session.history.clear()
                captured_report = None
                list(pipeline.run(session, audio_tuple))
                if captured_report:
                    metrics["stt_ms"].append(captured_report["stt_ms"])
                    metrics["llm_first_token_ms"].append(captured_report["llm_first_token_ms"])
                    metrics["llm_total_ms"].append(captured_report["llm_total_ms"])
                    metrics["tts_first_chunk_ms"].append(captured_report["tts_first_chunk_ms"])
                    metrics["tts_total_ms"].append(captured_report["tts_total_ms"])
                    metrics["first_audio_ms"].append(captured_report["first_audio_ms"])
                    metrics["turn_ms"].append(captured_report["turn_ms"])
                    total_runs += 1

        summary = {}
        for key, values in metrics.items():
            summary[key] = compute_stats(values)

        lang_results[lang] = summary
        print(
            f"  {lang} - p50 TTFA: {summary.get('first_audio_ms', {}).get('p50', 0):.1f} ms | p95: {summary.get('first_audio_ms', {}).get('p95', 0):.1f} ms"
        )

    report = {
        "hardware": get_hardware_info(args.model),
        "timestamp": datetime.datetime.now(datetime.UTC).isoformat(),
        "mode": args.mode,
        "runs": total_runs,
        "results_by_language": lang_results,
    }

    results_dir.mkdir(parents=True, exist_ok=True)
    if args.output:
        out_file = Path(args.output)
    else:
        date_str = datetime.datetime.now().strftime("%Y%m%d")
        prefix = "baseline" if args.mode == "baseline" else "streaming"
        out_file = results_dir / f"{prefix}_{date_str}.json"

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(json.dumps(report, indent=2))
    print(f"\nSuccess. Wrote benchmark report to {out_file}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
